"""Builds dist/SDR Servo Tuning Tool.app - a real macOS application bundle around this project's own venv, so the
Dock knows the tool as itself: its own icon while it runs, while it quits, and when it is kept in the Dock (user,
2026-09-26, a screen recording of the quit: "while closing the application why our logo goes and old logo appears
again" - a bare `python main.py` process belongs to Python.app in the Dock's eyes, and the Dock draws the tile's
removal with THAT bundle's icon, the Python rocket, whatever icon the running app had set; measured frame by frame,
and no in-process trick - leaving the Dock before exit, from inside or outside the event loop - changes it).

The bundle holds its OWN COPY of the Python interpreter binary (the one the venv's python really execs,
Python.app/Contents/MacOS/Python - it links the framework by absolute path, so a copy runs anywhere; re-signed ad hoc,
since the copy fails Python.org's hardened-runtime signature outside its own bundle and the kernel kills it), a
launcher script the Finder/Dock runs that `exec`s that interpreter on main.py with the venv's site-packages on
PYTHONPATH (one process, the PID the Dock launched), an Info.plist naming the tool and its icon, and the .icns
`tools/make_app_icon.py` writes. A process whose executable lives in this bundle is the TOOL to the Dock, however it
was started - so main.py re-launches itself through this interpreter when run from PyCharm or a terminal
(`sdr_tuner/dock_identity.py`; the bundle is built on demand). Paths are this machine's, so the bundle is generated,
not committed (`dist/` is ignored by git).

Run: .venv/bin/python tools/make_app_bundle.py
"""
import os
import plistlib
import shutil
import stat
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from sdr_tuner import __version__     # noqa: E402
from sdr_tuner import dock_identity   # noqa: E402

NAME = dock_identity.BUNDLE_NAME
BUNDLE = dock_identity.BUNDLE
ICNS = ROOT / "sdr_tuner" / "data" / "app_icon.icns"
LAUNCHER = """#!/bin/bash
# {name} - launches the tool from its project folder through this bundle's own interpreter copy, with the project's
# venv on PYTHONPATH (generated by tools/make_app_bundle.py; the paths are this machine's). exec keeps it one
# process: the one the Dock launched, whose executable lives in this bundle - so the Dock uses this bundle's icon.
cd "{root}" || exit 1
export PYTHONPATH="{site}${{PYTHONPATH:+:$PYTHONPATH}}"
export {no_relaunch}=1
exec "{interpreter}" main.py "$@"
"""


def sign(bundle):
    """An ad-hoc signature over the bundle (the interpreter copy is killed at launch without one); False if codesign
    is missing or refuses - the bundle then still works for LaunchServices launches through the launcher script."""
    if shutil.which("codesign") is None:
        return False
    # the interpreter copy first: a bundle signature covers only the main executable (the launcher script) and
    # leaves a nested Mach-O file with whatever signature it carried - Python.org's, which fails outside Python.app
    interp = dock_identity.bundle_interpreter(bundle)
    ok = True
    for target in (interp, bundle):
        done = subprocess.run(["codesign", "--force", "--sign", "-", str(target)], capture_output=True, text=True)
        ok = ok and done.returncode == 0
    return ok


def build(bundle=None):
    bundle = Path(bundle) if bundle else BUNDLE
    if not ICNS.exists():
        sys.exit(f"{ICNS.relative_to(ROOT)} is missing - run tools/make_app_icon.py first")
    if bundle.exists():
        shutil.rmtree(bundle)
    contents = bundle / "Contents"
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir()
    interpreter = dock_identity.bundle_interpreter(bundle)
    source = dock_identity.real_executable()
    if source is not None and source.exists():
        shutil.copy2(source, interpreter)                    # the interpreter binary itself, not the venv's stub
        interpreter.chmod(interpreter.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        dock_identity.stamp_path(bundle).write_text(dock_identity.source_stamp(source))   # what it was copied from
    launcher = contents / "MacOS" / NAME
    launcher.write_text(LAUNCHER.format(name=NAME, root=ROOT, site=dock_identity.site_packages(),
                                        interpreter=interpreter, no_relaunch=dock_identity.NO_RELAUNCH_ENV))
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    shutil.copy(ICNS, contents / "Resources" / "app.icns")
    (contents / "PkgInfo").write_text("APPL????")
    with open(contents / "Info.plist", "wb") as fh:
        plistlib.dump({
            "CFBundleName": NAME,
            "CFBundleDisplayName": NAME,
            "CFBundleIdentifier": "com.stimita.sdr-servo-tuning-tool",
            "CFBundleVersion": __version__,
            "CFBundleShortVersionString": __version__,
            "CFBundleExecutable": NAME,
            "CFBundleIconFile": "app.icns",
            "CFBundlePackageType": "APPL",
            "CFBundleInfoDictionaryVersion": "6.0",
            "LSMinimumSystemVersion": "11.0",
            "NSHighResolutionCapable": True,
            "NSHumanReadableCopyright": "STIMITA MOTION CONTROL",
        }, fh)
    os.utime(bundle)                                   # a fresh modification time: Finder and the Dock re-read the icon
    if source is not None and source.exists() and not sign(bundle):
        print("warning: the bundle could not be signed - its interpreter copy may be refused at launch", file=sys.stderr)
    return bundle


if __name__ == "__main__":
    print(f"built {build().relative_to(ROOT)}")
